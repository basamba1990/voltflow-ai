import { createClient } from "npm:@supabase/supabase-js@2.38.0";

// ✅ Robust CORS headers for all responses
const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
  'Access-Control-Allow-Methods': 'POST, OPTIONS',
  'Content-Type': 'application/json',
};

// ✅ Mesh generation functions
function generateStructuredMesh(dimensions: [number, number, number], spacing: [number, number, number]) {
  const [nx, ny, nz] = dimensions;
  const [dx, dy, dz] = spacing;
  const temperatureValues: number[] = [];
  const center = [((nx - 1) * dx) / 2, ((ny - 1) * dy) / 2, ((nz - 1) * dz) / 2];
  const maxDim = Math.max(nx * dx, ny * dy, nz * dz);

  for (let k = 0; k < nz; k++) {
    for (let j = 0; j < ny; j++) {
      for (let i = 0; i < nx; i++) {
        const x = i * dx;
        const y = j * dy;
        const z = k * dz;
        const distance = Math.sqrt(
          Math.pow(x - center[0], 2) + Math.pow(y - center[1], 2) + Math.pow(z - center[2], 2)
        );
        const temperature = 25 + 175 * Math.exp(-distance / (maxDim / 3));
        temperatureValues.push(temperature);
      }
    }
  }
  return { temperatureValues };
}

function generateVTKFile(config: { dimensions: number[]; spacing: number[] }, temperatureData: number[]) {
  const [nx, ny, nz] = config.dimensions;
  const [dx, dy, dz] = config.spacing;
  let vtk = `# vtk DataFile Version 4.2\nGenerated by Industrial Simulation\nASCII\nDATASET STRUCTURED_GRID\nDIMENSIONS ${nx} ${ny} ${nz}\nPOINTS ${nx * ny * nz} float\n`;
  for (let k = 0; k < nz; k++) {
    for (let j = 0; j < ny; j++) {
      for (let i = 0; i < nx; i++) {
        vtk += `${i * dx} ${j * dy} ${k * dz}\n`;
      }
    }
  }
  vtk += `\n\nPOINT_DATA ${nx * ny * nz}\nSCALARS temperature float 1\nLOOKUP_TABLE default\n`;
  for (const t of temperatureData) vtk += `${t.toFixed(4)}\n`;
  return vtk;
}

// ✅ Main function handler
Deno.serve(async (req) => {
  console.log("🚀 [Simulate] Function called. Method:", req.method);

  if (req.method === 'OPTIONS') {
    return new Response('ok', { headers: corsHeaders });
  }

  if (req.method !== 'POST') {
    return new Response(JSON.stringify({ success: false, error: "Method not allowed" }), { status: 405, headers: corsHeaders });
  }

  let simId: string | null = null;
  let userId: string | null = null;
  let config: any = null;

  try {
    const body = await req.json();
    console.log("📦 Payload reçu:", JSON.stringify(body).substring(0, 200));

    // ✅ GESTION DU PAYLOAD (Direct ou via Webhook Supabase)
    if (body.type === 'INSERT' && body.table === 'simulations' && body.record) {
      // C'est un Webhook Supabase
      console.log("🔗 Détection d'un appel via Database Webhook");
      simId = body.record.id;
      userId = body.record.user_id;
      config = {
        geometry_config: body.record.geometry_config,
        boundary_conditions: body.record.boundary_conditions,
        material_id: body.record.material_id,
        mesh_density: body.record.mesh_density,
        solver_type: body.record.solver_type
      };
    } else {
      // C'est un appel direct du Frontend
      console.log("💻 Détection d'un appel direct du Frontend");
      simId = body.simulation_id;
      userId = body.user_id;
      config = body.config;
    }

    if (!simId || !userId) {
      throw new Error(`Paramètres manquants: simId=${simId}, userId=${userId}`);
    }

    const SUPABASE_URL = Deno.env.get('SUPABASE_URL');
    const SUPABASE_SERVICE_ROLE_KEY = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');
    const supabase = createClient(SUPABASE_URL!, SUPABASE_SERVICE_ROLE_KEY!);

    // 1. Vérifier si la simulation doit être lancée (éviter les boucles si nécessaire)
    const { data: simulation } = await supabase
      .from('simulations')
      .select('*')
      .eq('id', simId)
      .single();

    if (!simulation) throw new Error("Simulation non trouvée");
    
    // Si déjà en cours ou terminée, on ne relance pas via Webhook pour éviter les boucles infinies
    if (body.type === 'INSERT' && (simulation.status === 'running' || simulation.status === 'completed')) {
      return new Response(JSON.stringify({ success: true, message: "Simulation déjà traitée" }), { headers: corsHeaders });
    }

    // 2. Mettre à jour le statut
    await supabase.from('simulations').update({
      status: 'running',
      progress: 20,
      started_at: new Date().toISOString()
    }).eq('id', simId);

    // 3. Logique de simulation (Fallback par défaut pour cet exemple)
    const meshDensity = simulation.mesh_density || 'medium';
    let dimensions: [number, number, number] = [30, 30, 30];
    let spacing: [number, number, number] = [3.33, 3.33, 3.33];

    const { temperatureValues } = generateStructuredMesh(dimensions, spacing);
    const vtkContent = generateVTKFile({ dimensions, spacing }, temperatureValues);
    const filePath = `${userId}/${simId}_result.vtk`;

    await supabase.storage.from('simulation-files').upload(filePath, new Blob([vtkContent]), {
      contentType: 'application/octet-stream',
      upsert: true
    });

    const { data: urlData } = supabase.storage.from('simulation-files').getPublicUrl(filePath);

    // 4. Sauvegarder les résultats
    await supabase.from('simulation_results').insert({
      simulation_id: simId,
      user_id: userId,
      max_temperature: Math.max(...temperatureValues),
      min_temperature: Math.min(...temperatureValues),
      average_temperature: temperatureValues.reduce((a, b) => a + b, 0) / temperatureValues.length,
      result_files: { vtk_url: urlData.publicUrl, source: 'webhook_auto' }
    });

    // 5. Finaliser
    await supabase.from('simulations').update({
      status: 'completed',
      progress: 100,
      completed_at: new Date().toISOString()
    }).eq('id', simId);

    return new Response(JSON.stringify({ success: true, simulation_id: simId }), { headers: corsHeaders });

  } catch (error: any) {
    console.error('💥 Erreur:', error.message);
    if (simId) {
      const SUPABASE_URL = Deno.env.get('SUPABASE_URL');
      const SUPABASE_SERVICE_ROLE_KEY = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY');
      const supabase = createClient(SUPABASE_URL!, SUPABASE_SERVICE_ROLE_KEY!);
      await supabase.from('simulations').update({ status: 'failed', error_message: error.message }).eq('id', simId);
    }
    return new Response(JSON.stringify({ success: false, error: error.message }), { status: 500, headers: corsHeaders });
  }
});
